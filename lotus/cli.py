@cli.command()
def status():
    """Show Lotus status: active agents, queue, recent PRs."""
    try:
        sections = {
            "Active agents": (
                [
                    "gh",
                    "run",
                    "list",
                    "--workflow=agent-dispatch.yml",
                    "--status=in_progress",
                    "--json",
                    "headBranch,startedAt",
                ],
                lambda r: f"  → {r['headBranch']} (started {r['startedAt']})",
            ),
            "Queued issues": (
                [
                    "gh",
                    "issue",
                    "list",
                    "--label",
                    "lotus:queued",
                    "--json",
                    "number,title",
                ],
                lambda r: f"  → #{r['number']}: {r['title']}",
            ),
            "Open AI PRs": (
                [
                    "gh",
                    "pr",
                    "list",
                    "--label",
                    "lotus:ai-generated",
                    "--json",
                    "number,title,headRefName",
                ],
                lambda r: f"  → #{r['number']}: {r['title']} ({r['headRefName']})",
            ),
            "Needs human help": (
                [
                    "gh",
                    "issue",
                    "list",
                    "--label",
                    "lotus:needs-human",
                    "--json",
                    "number,title",
                ],
                lambda r: f"  → #{r['number']}: {r['title']}",
            ),
        }

        click.echo("=== Lotus Status ===\n")
        for label, (cmd, fmt) in sections.items():
            try:
                result = subprocess.run(cmd, capture_output=True, text=True, check=True)
                items = yaml.safe_load(result.stdout) or []
                click.echo(f"{label}: {len(items)}")
                for item in items:
                    click.echo(fmt(item))
            except FileNotFoundError:
                click.echo(f"{label}: (gh CLI not found)")
            except subprocess.CalledProcessError as e:
                stderr = e.stderr.strip()
                msg = stderr.splitlines()[0] if stderr else "gh command failed"
                click.echo(f"{label}: (error — {msg})")
            click.echo()

    except Exception as e:
        click.echo(f"Error: {e}")


